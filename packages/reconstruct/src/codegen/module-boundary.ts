/**
 * The module-library pass: one library per Blizzard module, with the original
 * import graph as the include rule.
 *
 * It runs on the finished tree (stage 2, after the globals headers exist) and
 * does four things:
 *
 *  1. Reads every reference the emitted code makes - per function body in a
 *     .cpp, per header for inline bodies and by-value types - and resolves it to
 *     the module that owns the symbol (functions and globals by Ghidra namespace,
 *     types by the header that defines them).
 *  2. Lints each cross-module reference against the graph (`module-dag.tsv`): a
 *     reference the original's import tables did not allow is a misfiled symbol,
 *     not something to suppress.
 *  3. Makes the headers say it. Every header of module D opens with a gate that
 *     fails the compile unless the including module may see D, and the function
 *     declarations no other module references move into a block only D's own
 *     translation units compile. The externs globals.h used to carry go to the
 *     owning module's data header, split the same way.
 *  4. Writes `<D>/<D>.public.h`: the headers of D that hold what other modules use.
 *
 * Includes stay rooted at the tree (`#include "D2Common/ITEMS/Items.h"`) as the
 * layout spec fixes them, so the include PATH cannot separate modules; the gates
 * do, and with every gate macro undefined (the monolithic build) the headers
 * compile exactly as before.
 */

import type { AnalyzedDataSymbol, ExtractedFunction, SourceFile } from '../types.js';
import {
  ModuleGraph, MODULE_BUILD_MACRO, moduleMacro, seesMacro,
} from '../modules/module-libraries.js';
import { scanReferences } from './needle-index.js';
import { emittedFunctionName, DECLS_BEGIN_MARKER, DECLS_END_MARKER, DECL_MARKER, DECL_END_MARKER, TYPE_MARKER, TYPE_END_MARKER } from './header.js';
import { sanitizeSymbolName, type ModuleExternDecl } from './globals-header.js';

/** The banner every generated file opens with (its dash is U+2014, as elsewhere). */
const BANNER = `// Auto-generated by ghidra-mcp ${String.fromCharCode(0x2014)} DO NOT EDIT`;

export type ReferenceKind = 'call' | 'global' | 'type';

export interface ModuleReference {
  kind: ReferenceKind;
  userModule: string;
  userFile: string;
  /** The referencing function's address, or `header`/`data` for text outside a body. */
  source: string;
  owner: string;
  symbol: string;
  verdict: 'allowed' | 'excepted' | 'violation';
}

export interface ModuleBoundaryInput {
  graph: ModuleGraph;
  files: Map<string, SourceFile>;
  functions: readonly ExtractedFunction[];
  /** The externally visible globals (scope 'global'). */
  globals: readonly AnalyzedDataSymbol[];
  typeOwnerMap: ReadonlyMap<string, string>;
  /** `globals/globals.h`: what is left of it after the hand-off. */
  globalsPath: string;
  globalOwner: (g: AnalyzedDataSymbol) => string | undefined;
  moduleExterns: Map<string, ModuleExternDecl[]>;
  /** Names globals.h still declares itself. */
  rootProvides: ReadonlySet<string>;
  /** The include/forward-declaration/definition lines a module data header needs for its globals. */
  typePrelude: (globals: AnalyzedDataSymbol[]) => string[];
}

export interface ModuleBoundaryResult {
  references: ModuleReference[];
  /** Report files, path -> TSV text. */
  reports: Map<string, string>;
  summary: string[];
}

export const normalizeAddress = (a: string | undefined): string =>
  (a ?? '').slice((a ?? '').lastIndexOf(':') + 1).toLowerCase().replace(/^0x/, '').padStart(8, '0');

/** `// 1.14d: 00525fb0` - the line the emitter writes above every definition. */
const DEFINITION_LINE = /^\/\/ [^:\s]+: ([0-9a-fA-F]{8})$/;

export function headerGate(module: string): string[] {
  return [
    `#if defined(${MODULE_BUILD_MACRO}) && !defined(${seesMacro(module)})`,
    `#error "${module} header: this module may not use ${module} (original DLL import graph)"`,
    '#endif',
  ];
}

export function privateOpen(module: string): string {
  return `#if !defined(${MODULE_BUILD_MACRO}) || defined(${moduleMacro(module)})`;
}

interface FnEntry { address: string; qualified: string; module: string | undefined }

/** Split a .cpp at the emitter's definition lines: [source, text] per body, `data` for the rest. */
export function splitDefinitions(content: string): Array<[string, string]> {
  const out: Array<[string, string]> = [];
  let source = 'data';
  let buf: string[] = [];
  for (const line of content.split('\n')) {
    const m = DEFINITION_LINE.exec(line);
    if (m) {
      if (buf.length) out.push([source, buf.join('\n')]);
      source = m[1].toLowerCase();
      buf = [];
      continue;
    }
    buf.push(line);
  }
  if (buf.length) out.push([source, buf.join('\n')]);
  return out;
}

/** A header's marked groups, and its text without them: what every includer compiles. */
export function readGroups(content: string): {
  decls: Array<{ address: string; text: string }>;
  types: Array<{ name: string; text: string }>;
  rest: string;
} {
  const decls: Array<{ address: string; text: string }> = [];
  const types: Array<{ name: string; text: string }> = [];
  const rest: string[] = [];
  let group: { kind: 'decl' | 'type'; key: string; lines: string[] } | undefined;
  for (const line of content.split('\n')) {
    if (line.startsWith(DECL_MARKER)) { group = { kind: 'decl', key: normalizeAddress(line.slice(DECL_MARKER.length)), lines: [] }; continue; }
    if (line.startsWith(TYPE_MARKER)) { group = { kind: 'type', key: line.slice(TYPE_MARKER.length), lines: [] }; continue; }
    if (group && (line === DECL_END_MARKER || line === TYPE_END_MARKER)) {
      if (group.kind === 'decl') decls.push({ address: group.key, text: group.lines.join('\n') });
      else types.push({ name: group.key, text: group.lines.join('\n') });
      group = undefined;
      continue;
    }
    if (group) group.lines.push(line); else rest.push(line);
  }
  return { decls, types, rest: rest.join('\n') };
}

/**
 * Resolve the marked declarations: public ones stay, the rest move into the
 * module-private block where the declaration list ends. A header outside every
 * module only loses its markers.
 */
export function splitHeaderDeclarations(
  content: string,
  module: string | undefined,
  isPublic: (address: string) => boolean,
  isPublicType: (name: string) => boolean = () => true,
): { content: string; publicCount: number; privateCount: number; privateTypes: number } {
  const out: string[] = [];
  let pending: string[] = [];
  let group: string[] | undefined;
  let groupAddr = '';
  let publicCount = 0;
  let privateCount = 0;
  let privateTypes = 0;
  let typeGroup: { name: string; lines: string[] } | undefined;
  for (const line of content.split('\n')) {
    // A type stays where the topological order put it; a private one is gated in place.
    if (line.startsWith(TYPE_MARKER)) { typeGroup = { name: line.slice(TYPE_MARKER.length), lines: [] }; continue; }
    if (line === TYPE_END_MARKER && typeGroup) {
      if (module === undefined || isPublicType(typeGroup.name)) out.push(...typeGroup.lines);
      else { out.push(privateOpen(module), ...typeGroup.lines, `#endif // ${moduleMacro(module)}`); privateTypes++; }
      typeGroup = undefined;
      continue;
    }
    if (typeGroup) { typeGroup.lines.push(line); continue; }
    if (line === DECLS_BEGIN_MARKER) continue;
    if (line.startsWith(DECL_MARKER)) { group = []; groupAddr = normalizeAddress(line.slice(DECL_MARKER.length)); continue; }
    if (line === DECL_END_MARKER && group) {
      if (module === undefined || isPublic(groupAddr)) { out.push(...group); publicCount++; }
      else { pending.push(...group); privateCount++; }
      group = undefined;
      continue;
    }
    if (group) { group.push(line); continue; }
    if (line === DECLS_END_MARKER) {
      if (pending.length > 0 && module !== undefined) {
        out.push('// Module-private: no other module references these', privateOpen(module), ...pending, `#endif // ${moduleMacro(module)}`);
      }
      pending = [];
      continue;
    }
    out.push(line);
  }
  return { content: out.join('\n'), publicCount, privateCount, privateTypes };
}

/** The gate after `#pragma once` (or first, when the header has none). */
export function insertHeaderGate(content: string, module: string): string {
  const lines = content.split('\n');
  const at = lines.indexOf('#pragma once');
  lines.splice(at < 0 ? 0 : at + 1, 0, ...headerGate(module));
  return lines.join('\n');
}

export function applyModuleBoundaries(input: ModuleBoundaryInput): ModuleBoundaryResult {
  const { graph, files } = input;

  // Symbol owners.
  const fnIndex = new Map<string, FnEntry[]>();
  for (const f of input.functions) {
    if (!f.name || f.isLibrary || f.isExternal) continue;
    const name = emittedFunctionName(f);
    const qualified = f.namespace ? `${f.namespace}::${name}` : name;
    const list = fnIndex.get(name) ?? [];
    list.push({ address: normalizeAddress(f.address), qualified, module: graph.moduleOfNamespace(f.namespace) });
    fnIndex.set(name, list);
  }
  const globalOwnerByName = new Map<string, string | null>();
  const globalOwnersByName = new Map<string, Set<string>>();
  for (const g of input.globals) {
    if (g.scope !== 'global') continue;
    const name = sanitizeSymbolName(g.suggestedName || g.name);
    const owner = input.globalOwner(g) ?? null;
    const held = globalOwnerByName.get(name);
    // One name, two owners: the reference cannot be attributed by name alone.
    globalOwnerByName.set(name, held === undefined || held === owner ? owner : null);
    if (owner) {
      const set = globalOwnersByName.get(name) ?? new Set<string>();
      set.add(owner);
      globalOwnersByName.set(name, set);
    }
  }
  const typeOwner = new Map<string, string>();
  for (const [type, header] of input.typeOwnerMap) {
    const m = graph.moduleOfPath(header);
    if (m) typeOwner.set(type, m);
  }

  // References.
  const references: ModuleReference[] = [];
  const publicFns = new Map<string, Set<string>>();
  const publicGlobals = new Map<string, Set<string>>();
  const publicTypes = new Map<string, Set<string>>();
  const mark = (map: Map<string, Set<string>>, module: string, key: string) => {
    const s = map.get(module) ?? new Set<string>();
    s.add(key);
    map.set(module, s);
  };
  let ambiguous = 0;
  const record = (kind: ReferenceKind, userModule: string, userFile: string, source: string, owner: string, symbol: string) => {
    const verdict = graph.mayUse(userModule, owner) ? 'allowed'
      : graph.excepted(userModule, owner, symbol) ? 'excepted' : 'violation';
    references.push({ kind, userModule, userFile, source, owner, symbol, verdict });
  };
  const scan = (text: string, userModule: string, userFile: string, source: string, header: boolean) => {
    const refs = scanReferences(text);
    for (const id of refs.identifiers) {
      const fns = fnIndex.get(id);
      if (fns) {
        let candidates = fns.filter(c => c.module !== undefined);
        const written = refs.qualified.get(id);
        if (written && candidates.length > 1) {
          const byQualifier = candidates.filter(c => [...written].some(w => c.qualified === w || c.qualified.endsWith(`::${w}`)));
          if (byQualifier.length > 0) candidates = byQualifier;
        }
        let modules = new Set(candidates.map(c => c.module!));
        if (modules.size > 1 && modules.has(userModule)) {
          // An unqualified name resolves to the user's own namespace first.
          candidates = candidates.filter(c => c.module === userModule);
          modules = new Set([userModule]);
        }
        if (modules.size > 1) ambiguous++;
        else if (modules.size === 1) {
          const owner = [...modules][0];
          if (owner !== userModule) {
            record('call', userModule, userFile, source, owner, candidates[0].qualified);
            for (const c of candidates) mark(publicFns, owner, c.address);
          } else if (header) {
            // An inline body in a header compiles in every includer.
            for (const c of candidates) mark(publicFns, owner, c.address);
          }
        }
      }
      const gOwner = globalOwnerByName.get(id);
      if (gOwner && gOwner !== userModule) {
        record('global', userModule, userFile, source, gOwner, id);
        mark(publicGlobals, gOwner, id);
      }
      const tOwner = typeOwner.get(id);
      if (tOwner && tOwner !== userModule) {
        record('type', userModule, userFile, source, tOwner, id);
        mark(publicTypes, tOwner, id);
      }
    }
  };

  for (const [path, file] of files) {
    const module = file.type === 'implementation' ? graph.libraryOfPath(path) : graph.moduleOfPath(path);
    if (module === undefined) {
      // A root file (d2_platform.h's macros, globals.h, the shared units) is seen
      // from every module: whatever it names of a module is that module's public API.
      // Every identifier run, preprocessor lines included: a macro body is trivia to
      // the lexer, and a macro is exactly how d2_platform.h names a module function.
      for (const id of identifierRuns(file.content)) {
        for (const c of fnIndex.get(id) ?? []) if (c.module) mark(publicFns, c.module, c.address);
        for (const owner of globalOwnersByName.get(id) ?? []) mark(publicGlobals, owner, id);
        const t = typeOwner.get(id);
        if (t) mark(publicTypes, t, id);
      }
      continue;
    }
    if (file.type === 'implementation') {
      for (const [source, text] of splitDefinitions(file.content)) scan(text, module, path, source, false);
    } else if (file.type === 'header') {
      const g = readGroups(file.content);
      scan([g.rest, ...g.types.map(t => t.text)].join('\n'), module, path, 'header', true);
    }
  }

  // Public types: what another module names, what a public declaration or extern of
  // the module spells, what a header's own text outside the gated groups names (an
  // includer compiles it), and - to a fixpoint - every type a public type's
  // definition names.
  const typeDefs = new Map<string, Map<string, string>>();
  const publicSeeds = new Map<string, string[]>();
  for (const [path, file] of files) {
    if (file.type !== 'header') continue;
    const module = graph.moduleOfPath(path);
    if (module === undefined) continue;
    const g = readGroups(file.content);
    const defs = typeDefs.get(module) ?? new Map<string, string>();
    for (const t of g.types) defs.set(t.name, t.text);
    typeDefs.set(module, defs);
    const pub = publicFns.get(module);
    const seeds = publicSeeds.get(module) ?? [];
    seeds.push(g.rest, ...g.decls.filter(d => pub?.has(d.address)).map(d => d.text));
    publicSeeds.set(module, seeds);
  }
  for (const [module, decls] of input.moduleExterns) {
    const pub = publicGlobals.get(module);
    const seeds = publicSeeds.get(module) ?? [];
    seeds.push(...decls.filter(d => pub?.has(d.name)).map(d => d.decl));
    publicSeeds.set(module, seeds);
  }
  const publicTypeClosure = new Map<string, Set<string>>();
  for (const [module, defs] of typeDefs) {
    const pub = new Set<string>([...(publicTypes.get(module) ?? [])].filter(t => defs.has(t)));
    for (const text of publicSeeds.get(module) ?? []) {
      for (const id of scanReferences(text).identifiers) if (defs.has(id)) pub.add(id);
    }
    const work = [...pub];
    while (work.length > 0) {
      const t = work.pop()!;
      for (const id of scanReferences(defs.get(t) ?? '').identifiers) {
        if (defs.has(id) && !pub.has(id)) { pub.add(id); work.push(id); }
      }
    }
    publicTypeClosure.set(module, pub);
  }

  // Headers: gate and split.
  const headersWithPublic = new Map<string, Set<string>>();
  let publicDecls = 0;
  let privateDecls = 0;
  let privateTypes = 0;
  for (const [path, file] of files) {
    if (file.type !== 'header') continue;
    const module = graph.moduleOfPath(path);
    const pub = module ? publicFns.get(module) : undefined;
    const pubTypes = module ? publicTypeClosure.get(module) : undefined;
    const split = splitHeaderDeclarations(file.content, module, a => pub?.has(a) ?? false, t => pubTypes?.has(t) ?? false);
    let content = split.content;
    if (module !== undefined) {
      publicDecls += split.publicCount;
      privateDecls += split.privateCount;
      privateTypes += split.privateTypes;
      content = insertHeaderGate(content, module);
      if (split.publicCount > 0) mark(headersWithPublic, module, path);
    }
    if (content !== file.content) files.set(path, { ...file, content });
  }
  for (const [module, types] of publicTypes) {
    for (const t of types) {
      const h = input.typeOwnerMap.get(t);
      if (h && graph.moduleOfPath(h) === module) mark(headersWithPublic, module, h);
    }
  }

  // Module data headers: what globals.h declared for each module.
  const moduleGlobalsHeaders = new Map<string, string>();
  let publicExterns = 0;
  let privateExterns = 0;
  for (const [module, decls] of input.moduleExterns) {
    if (!graph.has(module)) continue;
    const path = graph.globalsHeaderOf(module);
    const pub = publicGlobals.get(module) ?? new Set<string>();
    const lines = [
      BANNER,
      '',
      `// Data of module ${module} that no single translation unit holds. Declarations another`,
      `// module references come first; the rest compile only inside ${module}.`,
      '',
      '#pragma once',
      ...headerGate(module),
      '',
      '#include <cstdint>',
      '#include <cstddef>',
      '#include "d2_platform.h"',
    ];
    if (decls.some(d => input.rootProvides.has(baseTypeName(d.global)))) lines.push(`#include "${input.globalsPath}"`);
    lines.push(...input.typePrelude(decls.map(d => d.global)));
    const render = (subset: ModuleExternDecl[]) => {
      let ns: string | undefined;
      for (const d of subset) {
        if (d.namespace !== ns) {
          if (ns) lines.push(`} // namespace ${ns}`);
          if (d.namespace) lines.push(`namespace ${d.namespace} {`);
          ns = d.namespace;
        }
        lines.push(d.decl);
      }
      if (ns) lines.push(`} // namespace ${ns}`);
    };
    const sorted = [...decls].sort((a, b) => (a.namespace ?? '').localeCompare(b.namespace ?? ''));
    const publicSet = sorted.filter(d => pub.has(d.name));
    const privateSet = sorted.filter(d => !pub.has(d.name));
    publicExterns += publicSet.length;
    privateExterns += privateSet.length;
    render(publicSet);
    if (privateSet.length > 0) {
      lines.push('', privateOpen(module));
      render(privateSet);
      lines.push(`#endif // ${moduleMacro(module)}`);
    }
    lines.push('');
    files.set(path, { path, content: lines.join('\n'), type: 'header', functions: [], includes: [] });
    moduleGlobalsHeaders.set(module, path);
  }

  // Every globals.h include becomes the data headers the file names.
  const globalsInclude = `#include "${input.globalsPath}"`;
  // A file that stops including globals.h keeps the type headers it reached through it.
  const throughGlobals = new Set<string>();
  // (globals.h used to carry the type includes the module data headers carry now.)
  for (const header of [input.globalsPath, ...moduleGlobalsHeaders.values()]) {
    for (const line of (files.get(header)?.content ?? '').split('\n')) {
      if (line.startsWith('#include "') && line.endsWith('"')) throughGlobals.add(line.slice(10, -1));
    }
  }
  throughGlobals.delete(input.globalsPath);
  // A type no header owns is defined (guarded) in each module data header whose
  // globals hold it; a file naming it includes one of those it may see.
  const definedIn = new Map<string, string[]>();
  for (const [module, header] of moduleGlobalsHeaders) {
    for (const line of (files.get(header)?.content ?? '').split('\n')) {
      if (!line.startsWith('#define D2_DEFINED_')) continue;
      const name = line.slice('#define D2_DEFINED_'.length).trim();
      const list = definedIn.get(name) ?? [];
      list.push(header);
      definedIn.set(name, list);
    }
    void module;
  }
  let rootIncludes = 0;
  let filesWithGlobals = 0;
  for (const [path, file] of files) {
    if (path === input.globalsPath || !file.content.includes(globalsInclude)) continue;
    filesWithGlobals++;
    const ids = scanReferences(file.content).identifiers;
    const wanted = new Set<string>();
    let root = false;
    const self = graph.libraryOfPath(path);
    for (const id of ids) {
      // A name several modules' data share: every declaring header the file may see.
      for (const owner of globalOwnersByName.get(id) ?? []) {
        const h = moduleGlobalsHeaders.get(owner);
        if (!h || h === path) continue;
        if (globalOwnerByName.get(id) === owner || self === undefined || graph.mayUse(self, owner)) wanted.add(h);
      }
      if (input.rootProvides.has(id)) root = true;
      const definers = definedIn.get(id);
      if (definers && !definers.includes(path)) {
        const own = graph.libraryOfPath(path);
        const visible = definers.find(h => {
          const m = graph.moduleOfPath(h);
          return own === undefined || m === undefined || graph.mayUse(own, m);
        });
        wanted.add(visible ?? definers[0]);
      }
      const typeHeader = input.typeOwnerMap.get(id);
      if (typeHeader && typeHeader !== path && throughGlobals.has(typeHeader)) wanted.add(typeHeader);
    }
    // What globals.h brought in transitively (a field chain's intermediate types) is
    // kept from every module this one may see.
    const own = graph.libraryOfPath(path);
    for (const h of throughGlobals) {
      const m = graph.moduleOfPath(h);
      if (h !== path && (m === undefined || own === undefined || graph.mayUse(own, m))) wanted.add(h);
    }
    if (root) rootIncludes++;
    const replacement = [...(root ? [input.globalsPath] : []), ...[...wanted].sort()]
      .map(h => `#include "${h}"`).join('\n');
    const content = file.content.split('\n')
      .map(l => (l === globalsInclude ? replacement : l)).join('\n');
    files.set(path, {
      ...file, content,
      includes: [...file.includes.filter(i => i !== input.globalsPath), ...(root ? [input.globalsPath] : []), ...wanted],
    });
  }

  // Public umbrella headers.
  for (const module of graph.names) {
    const headers = new Set(headersWithPublic.get(module) ?? []);
    const g = moduleGlobalsHeaders.get(module);
    if (g && (publicGlobals.get(module)?.size ?? 0) > 0) headers.add(g);
    if (headers.size === 0) continue;
    const path = graph.publicHeaderOf(module);
    if (files.has(path)) continue;
    const listed = [...headers].filter(h => files.has(h)).sort();
    const content = [
      BANNER,
      '',
      `// Public interface of ${module}: every header holding a function, global or type`,
      '// another module of the tree references. Ours, not original: the original public',
      '// headers are not in the evidence.',
      '',
      '#pragma once',
      ...headerGate(module),
      '',
      ...listed.map(h => `#include "${h}"`),
      '',
    ].join('\n');
    files.set(path, { path, content, type: 'header', functions: [], includes: listed });
  }

  // Reports.
  const reports = new Map<string, string>();
  const key = (r: ModuleReference) => `${r.userModule}>${r.owner}\t${r.kind}\t${r.userFile}\t${r.source}\t${r.symbol}`;
  const rows = references.filter(r => r.verdict !== 'allowed').sort((a, b) => key(a).localeCompare(key(b)));
  reports.set('module-dag.tsv', [
    'edge\tkind\tverdict\tuser_file\tsource\tsymbol',
    ...rows.map(r => `${r.userModule}->${r.owner}\t${r.kind}\t${r.verdict}\t${r.userFile}\t${r.source}\t${r.symbol}`),
  ].join('\n') + '\n');
  const api: string[] = ['module\tkind\tsymbol'];
  for (const [m, s] of [...publicFns].sort()) for (const a of [...s].sort()) api.push(`${m}\tfunction\t${a}`);
  for (const [m, s] of [...publicGlobals].sort()) for (const n of [...s].sort()) api.push(`${m}\tglobal\t${n}`);
  for (const [m, s] of [...publicTypes].sort()) for (const n of [...s].sort()) api.push(`${m}\ttype\t${n}`);
  reports.set('module-public-api.tsv', api.join('\n') + '\n');

  const violations = references.filter(r => r.verdict === 'violation');
  const byKind = (k: ReferenceKind) => violations.filter(r => r.kind === k).length;
  const edges = new Set(violations.map(r => `${r.userModule}->${r.owner}`));
  const summary = [
    `Module DAG: ${references.length} cross-module reference(s), ${violations.length} against the import graph ` +
      `(${byKind('call')} call/ref, ${byKind('global')} global, ${byKind('type')} type) on ${edges.size} edge(s); ` +
      `${references.filter(r => r.verdict === 'excepted').length} excepted; ${ambiguous} name(s) owned by several modules left unattributed`,
    `Module headers: ${publicDecls} public and ${privateDecls} module-private function declaration(s); ` +
      `${[...publicTypeClosure.values()].reduce((n, v) => n + v.size, 0)} public and ${privateTypes} module-private type definition(s); ` +
      `${moduleGlobalsHeaders.size} module data header(s), ${publicExterns} public and ${privateExterns} private extern(s)`,
    `globals.h: included by ${rootIncludes} of ${filesWithGlobals} file(s) that used to include it`,
  ];
  return { references, reports, summary };
}

function baseTypeName(g: AnalyzedDataSymbol): string {
  return (g.suggestedType || g.dataType || '')
    .replace(/\[[^\]]*\]/g, '').replace(/[*&]/g, '').replace(/\b(const|volatile|struct|union|enum)\b/g, '').trim();
}

/** Every maximal identifier run in a text, comments and directives included. */
export function identifierRuns(text: string): Set<string> {
  const out = new Set<string>();
  let i = 0;
  const isStart = (c: number) => (c >= 65 && c <= 90) || (c >= 97 && c <= 122) || c === 95;
  const isPart = (c: number) => isStart(c) || (c >= 48 && c <= 57);
  while (i < text.length) {
    const c = text.charCodeAt(i);
    if (isPart(c)) {
      let j = i;
      while (j < text.length && isPart(text.charCodeAt(j))) j++;
      if (isStart(c)) out.add(text.slice(i, j));
      i = j;
    } else i++;
  }
  return out;
}
