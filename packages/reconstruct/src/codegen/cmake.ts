/**
 * Generate a top-level CMakeLists.txt that includes subdirectories for each target
 */
export function generateTopLevelCMake(
  project: ReconstructedProject,
  targets: Map<string, ResolvedTarget>,
  hasUnsorted: boolean,
  options: ReconstructOptions
): string {
  const projectName = options.projectName || project.name || 'reconstructed';
  const lines: string[] = [];

  lines.push('#');
  lines.push(`# ${projectName} - Reconstructed Source Code`);
  lines.push('#');
  lines.push('# Generated by ghidra-mcp reconstruct tool');
  lines.push('#');
  lines.push('');
  lines.push('cmake_minimum_required(VERSION 3.16)');
  lines.push(`project(${sanitizeName(projectName)})`);
  lines.push('');
  lines.push('set(CMAKE_CXX_STANDARD 17)');
  lines.push('set(CMAKE_CXX_STANDARD_REQUIRED ON)');
  lines.push('set(CMAKE_EXPORT_COMPILE_COMMANDS ON)');
  lines.push('');

  lines.push('# Flags for Ghidra-decompiled code (32-bit Win32 binary)');
  lines.push('# -w silences the decompiled spelling\'s warning flood, -fms-extensions admits');
  lines.push('# the MSVC constructs. Strict C++ otherwise: no error is downgraded.');
  lines.push('if(MSVC)');
  lines.push('    add_compile_options(/W0)');
  lines.push('else()');
  lines.push('    add_compile_options(-w -fms-extensions)');
  lines.push('endif()');
  lines.push('');

  lines.push('# Targets');
  for (const [targetName] of targets) {
    lines.push(`add_subdirectory(${targetName})`);
  }
  if (hasUnsorted) {
    lines.push('add_subdirectory(unsorted)');
  }
  lines.push('');

  return lines.join('\n');
}

/**
 * Generate CMakeLists.txt for a single target
 */
export function generateTargetCMake(
  target: ResolvedTarget,
  targetDir: string,
  files: Map<string, SourceFile>,
  options: ReconstructOptions
): string {
  const lines: string[] = [];
  const cmakeName = target.config.cmakeName || sanitizeName(target.name);

  lines.push(`# ${target.name} target`);
  if (target.config.description) {
    lines.push(`# ${target.config.description}`);
  }
  lines.push('');

  // Source and header files in this target directory
  const { sources: sourceFiles, headers: headerFiles } = collectBuildFiles(files, targetDir);

  if (target.config.type === 'interface') {
    // Header-only INTERFACE library
    lines.push(`add_library(${cmakeName} INTERFACE)`);
    lines.push(`target_include_directories(${cmakeName} INTERFACE`);
    lines.push('    ${CMAKE_CURRENT_SOURCE_DIR}');
    lines.push('    ${CMAKE_CURRENT_SOURCE_DIR}/..');
    lines.push(')');
  } else {
    // Source files
    if (sourceFiles.length > 0) {
      lines.push('set(SOURCES');
      for (const source of sourceFiles) {
        lines.push(`    ${source}`);
      }
      lines.push(')');
      lines.push('');
    }

    if (headerFiles.length > 0) {
      lines.push('set(HEADERS');
      for (const header of headerFiles) {
        lines.push(`    ${header}`);
      }
      lines.push(')');
      lines.push('');
    }

    const libType = target.config.type === 'shared_library' ? 'SHARED' : 'STATIC';
    if (target.config.type === 'executable') {
      lines.push(`add_executable(${cmakeName} \${SOURCES} \${HEADERS})`);
    } else {
      lines.push(`add_library(${cmakeName} ${libType} \${SOURCES} \${HEADERS})`);
    }

    lines.push(`target_include_directories(${cmakeName} PUBLIC`);
    lines.push('    ${CMAKE_CURRENT_SOURCE_DIR}');
    lines.push('    ${CMAKE_CURRENT_SOURCE_DIR}/..');
    lines.push(')');
    lines.push('');

    // Dependencies
    if (target.config.dependencies && target.config.dependencies.length > 0) {
      const depNames = target.config.dependencies.map(dep => {
        // Look up the cmake name from the target config
        return sanitizeName(dep);
      });
      lines.push(`target_link_libraries(${cmakeName} PUBLIC ${depNames.join(' ')})`);
    }

    // Cross-target deps (informational)
    if (target.externalDeps.size > 0) {
      lines.push('');
      lines.push('# Cross-target dependencies (resolved at link time):');
      for (const [depTarget, funcs] of target.externalDeps) {
        lines.push(`#   ${depTarget}: ${funcs.slice(0, 5).join(', ')}${funcs.length > 5 ? '...' : ''}`);
      }
    }
  }

  lines.push('');
  return lines.join('\n');
}

/**
 * Generate CMakeLists.txt for unsorted functions
 */
export function generateUnsortedCMake(
  files: Map<string, SourceFile>,
  options: ReconstructOptions
): string {
  const lines: string[] = [];
  const cmakeName = sanitizeName((options.projectName || 'reconstructed') + '_unsorted');

  lines.push('# Unsorted functions (not assigned to any target)');
  lines.push('');

  const { sources: sourceFiles, headers: headerFiles } = collectBuildFiles(files, 'unsorted');

  if (sourceFiles.length > 0) {
    lines.push('set(SOURCES');
    for (const source of sourceFiles) {
      lines.push(`    ${source}`);
    }
    lines.push(')');
    lines.push('');
  }

  if (headerFiles.length > 0) {
    lines.push('set(HEADERS');
    for (const header of headerFiles) {
      lines.push(`    ${header}`);
    }
    lines.push(')');
    lines.push('');
  }

  lines.push(`add_library(${cmakeName} STATIC \${SOURCES} \${HEADERS})`);
  lines.push(`target_include_directories(${cmakeName} PUBLIC`);
  lines.push('    ${CMAKE_CURRENT_SOURCE_DIR}');
  lines.push('    ${CMAKE_CURRENT_SOURCE_DIR}/..');
  lines.push(')');
  lines.push('');

  return lines.join('\n');
}

/**
 * One static library per Blizzard module (project.json `moduleLibraries`).
 *
 * Each library compiles with `D2_MODULE_<itself>` and `D2_SEES_<m>` for every
 * module the original import graph lets it reach; the header gates
 * (codegen/module-boundary.ts) turn any other include into a compile error.
 * `target_link_libraries` follows the static imports. The executable links the
 * libraries whole, in `linkOrder`: the order decides which copy of a COMDAT the
 * linker keeps and the order of the static initializers, as the 1.14d link did.
 * Files outside every module (globals.cpp, _unnamespaced.cpp) form `d2_root`,
 * which may see everything - the transitional remainder, meant to end empty.
 */
export function generateModuleLibrariesCMake(
  project: ReconstructedProject,
  graph: ModuleGraph,
  options: ReconstructOptions,
): string {
  const { sources } = collectBuildFiles(project.files);
  const byLibrary = new Map<string, string[]>();
  const root: string[] = [];
  for (const src of sources) {
    const lib = graph.libraryOfPath(src);
    if (lib === undefined) { root.push(src); continue; }
    const list = byLibrary.get(lib) ?? [];
    list.push(src);
    byLibrary.set(lib, list);
  }
  const libraries = graph.linkOrder().filter(m => (byLibrary.get(m)?.length ?? 0) > 0);
  const has = new Set(libraries);
  const projectName = sanitizeName(options.projectName || project.name || 'reconstructed');

  const L: string[] = [];
  L.push('# Generated by ghidra-reconstruct: one library per original module.');
  L.push('#');
  L.push('#   cmake -S . -B build -DCMAKE_TOOLCHAIN_FILE=<mingw-i686 toolchain>');
  L.push('#');
  L.push('# A module may include another module\'s headers only if the original DLL import');
  L.push('# graph reaches it; every header checks D2_SEES_<module> and fails the compile');
  L.push('# otherwise. Declarations no other module references compile only inside their');
  L.push('# own module (D2_MODULE_<module>).');
  L.push('');
  L.push('cmake_minimum_required(VERSION 3.24)');
  L.push(`project(${projectName} LANGUAGES C CXX)`);
  L.push('set(CMAKE_EXPORT_COMPILE_COMMANDS ON)');
  L.push('');
  L.push('# Flags every module shares. Includes are rooted at the tree; the directories that');
  L.push('# hold headers are on the path too, for the few by bare name.');
  L.push('add_library(d2_flags INTERFACE)');
  L.push('target_compile_features(d2_flags INTERFACE cxx_std_17)');
  L.push(`target_compile_definitions(d2_flags INTERFACE ${MODULE_BUILD_MACRO})`);
  L.push('target_compile_options(d2_flags INTERFACE');
  L.push('    "$<$<COMPILE_LANGUAGE:CXX>:-w;-fms-extensions;-fwrapv>"');
  L.push('    "$<$<COMPILE_LANGUAGE:CXX>:SHELL:-include ${CMAKE_CURRENT_SOURCE_DIR}/d2_platform.h>")');
  L.push('target_include_directories(d2_flags INTERFACE');
  L.push('    ${CMAKE_CURRENT_SOURCE_DIR}');
  for (const dir of getIncludeDirectories(project)) L.push(`    ${dir}`);
  L.push(')');
  L.push('');

  const emitLibrary = (name: string, files: string[], defs: string[], links: string[], note: string) => {
    L.push(`# ${note}`);
    L.push(`add_library(${name} STATIC`);
    for (const f of files) L.push(`    ${f}`);
    L.push(')');
    L.push(`target_compile_definitions(${name} PRIVATE`);
    for (const d of defs) L.push(`    ${d}`);
    L.push(')');
    L.push(`target_link_libraries(${name} PUBLIC ${['d2_flags', ...links].join(' ')})`);
    L.push('');
  };

  for (const m of libraries) {
    const sees = [...graph.reachable(m)].sort().map(seesMacro);
    const links = graph.importsOf(m).filter(d => has.has(d));
    const cfg = graph.config.modules[m];
    const note = cfg.embedded
      ? `${m}: compiled into each module that used it; one copy here, visible to every module`
      : `${m}: imports ${graph.importsOf(m).join(', ') || '(none)'}` +
        ((cfg.loads ?? []).length ? `; loads ${cfg.loads!.join(', ')}` : '') +
        (cfg.evidence ? ` (${cfg.evidence})` : '');
    emitLibrary(m, byLibrary.get(m)!, [moduleMacro(m), ...sees], links, note);
  }
  if (root.length > 0) {
    const all = graph.names;
    emitLibrary('d2_root', root, [...all.map(moduleMacro), ...all.map(seesMacro)], [],
      'd2_root: files no module owns yet (transitional; meant to end empty)');
  }

  L.push('# The executable: every library whole, in the original link order.');
  L.push('file(WRITE ${CMAKE_CURRENT_BINARY_DIR}/d2_link_anchor.cpp "")');
  L.push('add_executable(d2 ${CMAKE_CURRENT_BINARY_DIR}/d2_link_anchor.cpp)');
  L.push('set_target_properties(d2 PROPERTIES WIN32_EXECUTABLE ON)');
  L.push('target_link_libraries(d2 PRIVATE');
  for (const m of [...libraries, ...(root.length > 0 ? ['d2_root'] : [])]) L.push(`    "$<LINK_LIBRARY:WHOLE_ARCHIVE,${m}>"`);
  L.push(')');
  L.push('');
  return L.join('\n');
}
