/**
 * Generate a top-level CMakeLists.txt that includes subdirectories for each target
 */
export function generateTopLevelCMake(
  project: ReconstructedProject,
  targets: Map<string, ResolvedTarget>,
  hasUnsorted: boolean,
  options: ReconstructOptions
): string {
  const projectName = options.projectName || project.name || 'reconstructed';
  const lines: string[] = [];

  lines.push('#');
  lines.push(`# ${projectName} - Reconstructed Source Code`);
  lines.push('#');
  lines.push('# Generated by ghidra-mcp reconstruct tool');
  lines.push('#');
  lines.push('');
  lines.push('cmake_minimum_required(VERSION 3.16)');
  lines.push(`project(${sanitizeName(projectName)})`);
  lines.push('');
  lines.push('set(CMAKE_CXX_STANDARD 17)');
  lines.push('set(CMAKE_CXX_STANDARD_REQUIRED ON)');
  lines.push('set(CMAKE_EXPORT_COMPILE_COMMANDS ON)');
  lines.push('');

  lines.push('# Flags for Ghidra-decompiled code (32-bit Win32 binary)');
  lines.push('# -w silences the decompiled spelling\'s warning flood, -fms-extensions admits');
  lines.push('# the MSVC constructs. Strict C++ otherwise: no error is downgraded.');
  lines.push('if(MSVC)');
  lines.push('    add_compile_options(/W0)');
  lines.push('else()');
  lines.push('    add_compile_options(-w -fms-extensions)');
  lines.push('endif()');
  lines.push('');

  lines.push('# Targets');
  for (const [targetName] of targets) {
    lines.push(`add_subdirectory(${targetName})`);
  }
  if (hasUnsorted) {
    lines.push('add_subdirectory(unsorted)');
  }
  lines.push('');

  return lines.join('\n');
}

/**
 * Generate CMakeLists.txt for a single target
 */
export function generateTargetCMake(
  target: ResolvedTarget,
  targetDir: string,
  files: Map<string, SourceFile>,
  options: ReconstructOptions
): string {
  const lines: string[] = [];
  const cmakeName = target.config.cmakeName || sanitizeName(target.name);

  lines.push(`# ${target.name} target`);
  if (target.config.description) {
    lines.push(`# ${target.config.description}`);
  }
  lines.push('');

  // Source and header files in this target directory
  const { sources: sourceFiles, headers: headerFiles } = collectBuildFiles(files, targetDir);

  if (target.config.type === 'interface') {
    // Header-only INTERFACE library
    lines.push(`add_library(${cmakeName} INTERFACE)`);
    lines.push(`target_include_directories(${cmakeName} INTERFACE`);
    lines.push('    ${CMAKE_CURRENT_SOURCE_DIR}');
    lines.push('    ${CMAKE_CURRENT_SOURCE_DIR}/..');
    lines.push(')');
  } else {
    // Source files
    if (sourceFiles.length > 0) {
      lines.push('set(SOURCES');
      for (const source of sourceFiles) {
        lines.push(`    ${source}`);
      }
      lines.push(')');
      lines.push('');
    }

    if (headerFiles.length > 0) {
      lines.push('set(HEADERS');
      for (const header of headerFiles) {
        lines.push(`    ${header}`);
      }
      lines.push(')');
      lines.push('');
    }

    const libType = target.config.type === 'shared_library' ? 'SHARED' : 'STATIC';
    if (target.config.type === 'executable') {
      lines.push(`add_executable(${cmakeName} \${SOURCES} \${HEADERS})`);
    } else {
      lines.push(`add_library(${cmakeName} ${libType} \${SOURCES} \${HEADERS})`);
    }

    lines.push(`target_include_directories(${cmakeName} PUBLIC`);
    lines.push('    ${CMAKE_CURRENT_SOURCE_DIR}');
    lines.push('    ${CMAKE_CURRENT_SOURCE_DIR}/..');
    lines.push(')');
    lines.push('');

    // Dependencies
    if (target.config.dependencies && target.config.dependencies.length > 0) {
      const depNames = target.config.dependencies.map(dep => {
        // Look up the cmake name from the target config
        return sanitizeName(dep);
      });
      lines.push(`target_link_libraries(${cmakeName} PUBLIC ${depNames.join(' ')})`);
    }

    // Cross-target deps (informational)
    if (target.externalDeps.size > 0) {
      lines.push('');
      lines.push('# Cross-target dependencies (resolved at link time):');
      for (const [depTarget, funcs] of target.externalDeps) {
        lines.push(`#   ${depTarget}: ${funcs.slice(0, 5).join(', ')}${funcs.length > 5 ? '...' : ''}`);
      }
    }
  }

  lines.push('');
  return lines.join('\n');
}

/**
 * Generate CMakeLists.txt for unsorted functions
 */
export function generateUnsortedCMake(
  files: Map<string, SourceFile>,
  options: ReconstructOptions
): string {
  const lines: string[] = [];
  const cmakeName = sanitizeName((options.projectName || 'reconstructed') + '_unsorted');

  lines.push('# Unsorted functions (not assigned to any target)');
  lines.push('');

  const { sources: sourceFiles, headers: headerFiles } = collectBuildFiles(files, 'unsorted');

  if (sourceFiles.length > 0) {
    lines.push('set(SOURCES');
    for (const source of sourceFiles) {
      lines.push(`    ${source}`);
    }
    lines.push(')');
    lines.push('');
  }

  if (headerFiles.length > 0) {
    lines.push('set(HEADERS');
    for (const header of headerFiles) {
      lines.push(`    ${header}`);
    }
    lines.push(')');
    lines.push('');
  }

  lines.push(`add_library(${cmakeName} STATIC \${SOURCES} \${HEADERS})`);
  lines.push(`target_include_directories(${cmakeName} PUBLIC`);
  lines.push('    ${CMAKE_CURRENT_SOURCE_DIR}');
  lines.push('    ${CMAKE_CURRENT_SOURCE_DIR}/..');
  lines.push(')');
  lines.push('');

  return lines.join('\n');
}
