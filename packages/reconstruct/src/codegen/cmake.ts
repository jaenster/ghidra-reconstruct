/**
 * CMakeLists.txt generation
 *
 * Generates a CMakeLists.txt file for building the reconstructed project
 */

import type { ReconstructedProject, ReconstructOptions, SourceFile } from '../types.js';
import type { ResolvedTarget } from '../targets/index.js';
import type { TargetConfig } from '../config/schema.js';

/**
 * Mac-only modules. The build targets the Windows binary and these functions
 * have no `win:` address, so they are written to the tree but never compiled.
 * Shared Win/Mac functions live in the normal Windows modules and are kept.
 */
const MAC_ONLY_PREFIXES = ['MacSpecific/', 'StormMac/'];

const isMacOnly = (path: string) => MAC_ONLY_PREFIXES.some((p) => path.startsWith(p));

/**
 * The one place that decides which project files become build inputs.
 *
 * The invariant this exists to hold is set equality: **the sources and headers
 * a build file names are exactly the files the generator writes**, minus the
 * single deliberate exclusion above. `writeProject` writes every entry of
 * `project.files`, so any list built from a different traversal - or with a
 * different filter - describes intent rather than the tree, and a configure
 * then fails on a source that was never written or silently drops one that
 * was.
 *
 * The same invariant was broken once before between the declaration side and
 * the definition side of the globals model, where two traversals disagreed
 * about which symbols were emittable; see `isEmittableGlobal` in
 * `globals-header.ts`. Four emitters here used to carry four copies of this
 * loop, three of which had already drifted - only one applied the Mac filter.
 * They all route through this function now so they cannot disagree again.
 *
 * @param dir  restrict to this directory and return paths relative to it
 */
export function collectBuildFiles(
  files: ReadonlyMap<string, SourceFile>,
  dir?: string
): { sources: string[]; headers: string[] } {
  const sources: string[] = [];
  const headers: string[] = [];
  const prefix = dir ? dir.replace(/\/+$/, '') + '/' : '';

  for (const [path, file] of files) {
    if (isMacOnly(path)) continue;
    if (prefix && !path.startsWith(prefix)) continue;
    const listed = path.slice(prefix.length);
    if (file.type === 'implementation') {
      sources.push(listed);
    } else if (file.type === 'header') {
      headers.push(listed);
    }
  }

  sources.sort();
  headers.sort();
  return { sources, headers };
}

/**
 * Generate CMakeLists.txt content
 */
export function generateCMakeLists(
  project: ReconstructedProject,
  options: ReconstructOptions
): string {
  const projectName = options.projectName || project.name || 'reconstructed';

  const lines: string[] = [];

  // Header comment with binary info
  lines.push('#');
  lines.push(`# ${projectName} - Reconstructed Source Code`);
  lines.push('#');
  lines.push('# Generated by ghidra-mcp reconstruct tool');
  if (project.programInfo) {
    lines.push('#');
    lines.push('# Original Binary Information:');
    lines.push(`#   Name:         ${project.programInfo.name}`);
    lines.push(`#   Format:       ${project.programInfo.format}`);
    lines.push(`#   Architecture: ${project.programInfo.architecture}`);
    lines.push(`#   Language:     ${project.programInfo.languageId}`);
    lines.push(`#   Image Base:   ${project.programInfo.imageBase}`);
    lines.push(`#   Endianness:   ${project.programInfo.endianness}`);
    lines.push(`#   Pointer Size: ${project.programInfo.pointerSize} bytes`);
    if (project.programInfo.compiler) {
      lines.push(`#   Compiler:     ${project.programInfo.compiler}`);
    }
  }
  lines.push('#');
  lines.push('');

  // CMake version and project
  lines.push('cmake_minimum_required(VERSION 3.16)');
  lines.push(`project(${sanitizeName(projectName)})`);
  lines.push('');

  // C++ standard
  lines.push('set(CMAKE_CXX_STANDARD 17)');
  lines.push('set(CMAKE_CXX_STANDARD_REQUIRED ON)');
  lines.push('set(CMAKE_EXPORT_COMPILE_COMMANDS ON)');
  lines.push('');

  // Compiler flags for decompiled code
  lines.push('# Flags for Ghidra-decompiled code (32-bit Win32 binary)');
  lines.push('# -w silences the warning flood the decompiled spelling produces;');
  lines.push('# -fms-extensions admits the MSVC constructs the binary was built with.');
  lines.push('# The tree compiles under strict C++ with no conformance relaxation, so');
  lines.push('# nothing here downgrades an error - a type-hole stays a hard failure.');
  lines.push('if(MSVC)');
  lines.push('    add_compile_options(/W0)');
  lines.push('else()');
  lines.push('    add_compile_options(-w -fms-extensions)');
  lines.push('endif()');
  lines.push('');

  const { sources: sourceFiles, headers: headerFiles } = collectBuildFiles(project.files);

  // Source files
  lines.push('# Source files');
  lines.push('set(SOURCES');
  for (const source of sourceFiles) {
    lines.push(`    ${source}`);
  }
  lines.push(')');
  lines.push('');

  // Header files
  lines.push('# Header files');
  lines.push('set(HEADERS');
  for (const header of headerFiles) {
    lines.push(`    ${header}`);
  }
  lines.push(')');
  lines.push('');

  // Get unique directories for include paths
  const includeDirs = getIncludeDirectories(project);

  // Include directories
  lines.push('# Include directories');
  lines.push('set(INCLUDE_DIRS');
  lines.push('    ${CMAKE_CURRENT_SOURCE_DIR}');
  for (const dir of includeDirs) {
    lines.push(`    ${dir}`);
  }
  lines.push(')');
  lines.push('');

  // Create library or executable
  lines.push('# Create library');
  lines.push(`add_library(\${PROJECT_NAME} STATIC \${SOURCES} \${HEADERS})`);
  lines.push('target_include_directories(${PROJECT_NAME} PUBLIC ${INCLUDE_DIRS})');
  lines.push('');

  // Optional: create an executable if there's a main function
  const hasMain = hasMainFunction(project);
  if (hasMain) {
    lines.push('# Executable (if main function exists)');
    lines.push(`add_executable(\${PROJECT_NAME}_exe \${SOURCES})`);
    lines.push('target_include_directories(${PROJECT_NAME}_exe PRIVATE ${INCLUDE_DIRS})');
    lines.push('');
  }

  // Installation rules
  lines.push('# Installation');
  lines.push('install(TARGETS ${PROJECT_NAME}');
  lines.push('    LIBRARY DESTINATION lib');
  lines.push('    ARCHIVE DESTINATION lib');
  lines.push(')');
  lines.push('install(FILES ${HEADERS} DESTINATION include)');
  lines.push('');

  // Export compile commands for IDE integration
  lines.push('# Export compile commands for IDE integration');
  lines.push('set(CMAKE_EXPORT_COMPILE_COMMANDS ON)');

  return lines.join('\n');
}

/**
 * Generate a simple Makefile alternative
 */
export function generateMakefile(
  project: ReconstructedProject,
  options: ReconstructOptions
): string {
  const projectName = options.projectName || project.name || 'reconstructed';

  const lines: string[] = [];

  // Variables
  lines.push(`CXX = g++`);
  lines.push(`CXXFLAGS = -std=c++17 -Wall -Wextra -I.`);
  lines.push(`TARGET = ${sanitizeName(projectName)}`);
  lines.push('');

  const { sources: sourceFiles } = collectBuildFiles(project.files);

  // Object files
  lines.push('SOURCES = \\');
  for (let i = 0; i < sourceFiles.length; i++) {
    const cont = i < sourceFiles.length - 1 ? ' \\' : '';
    lines.push(`    ${sourceFiles[i]}${cont}`);
  }
  lines.push('');

  lines.push('OBJECTS = $(SOURCES:.cpp=.o)');
  lines.push('');

  // Targets
  lines.push('all: $(TARGET)');
  lines.push('');

  lines.push('$(TARGET): $(OBJECTS)');
  lines.push('\t$(CXX) $(CXXFLAGS) -o $@ $^');
  lines.push('');

  lines.push('%.o: %.cpp');
  lines.push('\t$(CXX) $(CXXFLAGS) -c -o $@ $<');
  lines.push('');

  lines.push('clean:');
  lines.push('\trm -f $(OBJECTS) $(TARGET)');
  lines.push('');

  lines.push('.PHONY: all clean');

  return lines.join('\n');
}

/**
 * Get unique include directories from project structure
 */
function getIncludeDirectories(project: ReconstructedProject): string[] {
  const dirs = new Set<string>();

  for (const [path] of project.files) {
    const dir = path.split('/').slice(0, -1).join('/');
    if (dir) {
      dirs.add('${CMAKE_CURRENT_SOURCE_DIR}/' + dir);
    }
  }

  return Array.from(dirs).sort();
}

/**
 * Check if project has a main function
 */
function hasMainFunction(project: ReconstructedProject): boolean {
  for (const [, file] of project.files) {
    if (file.functions.includes('main') || file.functions.includes('_main')) {
      return true;
    }
  }
  return false;
}

/**
 * Sanitize name for use in CMake
 */
function sanitizeName(name: string): string {
  return name.replace(/[^a-zA-Z0-9_]/g, '_');
}

