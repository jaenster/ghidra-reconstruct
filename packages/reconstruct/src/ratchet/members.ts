/**
 * Closure members that are not MATCH themselves: release them when a compile proves their
 * records do not need the stored body.
 *
 * A match record keeps its file-static callees because VC8 gives a static function its own
 * register convention and may inline it, so the caller's bytes can follow the callee's body
 * (docs/ratchet.md, "A record"). For a member that is not MATCH itself that protection has a
 * price: every later fix of the member is vetoed for as long as the record holds the old body.
 * So after a measurement, every such member whose generated body differs from the kept one
 * (the apply's `ratchet-fresh.json`) is compiled into its unit in place of the kept one, beside
 * an unchanged compile of the same unit (`TrialCompiler`, the VC8 oracle's trial and judge):
 *
 * - every MATCH record holding it, and every other function of the unit that matched, still
 *   matches: the member is released (a `release.tsv` row naming exactly that body, with the
 *   reason). The next regen lets that body through, and the measurement after it re-captures
 *   the records with it and consumes the row (advance.ts).
 * - anything else (a MATCH lost, a compile that failed, a holder that does not match even
 *   unchanged): the member stays kept, and the row says why.
 *
 * A member whose generated body is the stored one vetoes nothing yet: its unit is the same
 * text either way, so its records' bytes cannot change. It stays in its records, which is what
 * catches the day its body changes (deploy 1163 lost 0057eab0 to a static callee's change);
 * that day it shows up here as differing and is compiled. Members that are MATCH, or that are
 * the root of a record of their own, are never released here: their own record decides.
 */
import { locate } from './ratchet.js';
import type { AuditRow } from './advance.js';
import { bodyHash, type RatchetRecord, type RatchetStore, type Release } from './store.js';
import type { SymbolIndex } from './symbol-index.js';

/** One text replacement in a unit: `from` must occur exactly once. */
export interface UnitEdit { from: string; to: string }

/** One compile: a unit of the measured tree (tree-relative path) with edits applied. */
export interface UnitTrial { file: string; edits: UnitEdit[] }

/** address -> status as the audit judges it, for every function of the unit; or why not. */
export interface TrialResult { statuses?: Map<string, string>; error?: string }

/** The verification step. vc8-verify.ts is the oracle's; tests pass their own. */
export interface TrialCompiler {
  compile(trials: UnitTrial[]): Promise<TrialResult[]>;
}

export type MemberStatus = 'released' | 'kept' | 'equal' | 'match' | 'own-record' | 'already-released' | 'no-holder';

export interface MemberRow {
  status: MemberStatus;
  address: string;
  name: string;
  /** The member's own audit status. */
  audit: string;
  /** Every record holding it: `address:audit[->trial status]`. */
  holders: string;
  /** How the outcome was checked: `compile`, `text`, `text+compile`, or empty. */
  verified: string;
  detail: string;
}

export interface MemberReleaseOptions {
  /** The generated bodies of the kept members (ratchet-fresh.json of the regen the tree merged). */
  fresh: Map<string, string>;
  /** Absent: nothing is compiled, so nothing is released. */
  compiler?: TrialCompiler;
  /** The evidence commit the audit measured, for the reason. */
  evidence: string;
  dryRun?: boolean;
  /**
   * A tree generated by the same regen (source/regen): for members without a fresh body,
   * its text of the member is compared with the measured tree's, which proves the unit
   * compiles the same text either way.
   */
  generated?: SymbolIndex;
  /** Compile this many units of `equal` members unchanged anyway, to show their holders match there. */
  sampleEqual?: number;
}

interface Candidate {
  address: string;
  name: string;
  audit: string;
  file: string;
  /** The definition the measured tree carries (the kept body). */
  kept: string;
  fresh: string;
  holders: RatchetRecord[];
}

const isMatch = (s: string | undefined) => s === 'MATCH';

/** What a trial costs: the functions that matched unchanged and do not in the trial. */
function lostIn(base: Map<string, string>, trial: Map<string, string>): string[] {
  return [...base].filter(([a, st]) => isMatch(st) && !isMatch(trial.get(a))).map(([a, st]) => `${a} ${st}->${trial.get(a) ?? 'MISSING'}`);
}

/** Can the base compile of a unit judge these holders at all? */
function baseProblem(base: TrialResult, holders: RatchetRecord[]): string | undefined {
  if (!base.statuses) return `the unchanged unit did not compile: ${base.error ?? 'no object'}`;
  const bad = holders.filter(h => !isMatch(base.statuses!.get(h.address)));
  return bad.length ? `holder ${bad.map(h => `${h.address} is ${base.statuses!.get(h.address) ?? 'MISSING'}`).join(', ')} in the unchanged compile` : undefined;
}

export async function releaseNonMatchMembers(index: SymbolIndex, store: RatchetStore, audit: Map<string, AuditRow>, opts: MemberReleaseOptions): Promise<MemberRow[]> {
  const records = store.list();
  const roots = new Set(records.map(r => r.address));
  const holdersOf = new Map<string, RatchetRecord[]>();
  const names = new Map<string, string>();
  for (const rec of records) {
    if (rec.kind !== 'match') continue;
    for (const m of rec.members.slice(1)) {
      holdersOf.set(m.address, [...(holdersOf.get(m.address) ?? []), rec]);
      names.set(m.address, m.name);
    }
  }
  const releases = store.releases();
  const released = new Set(releases.map(r => r.address));
  const st = (a: string) => audit.get(a)?.status ?? 'not in audit';
  const holderText = (hs: RatchetRecord[], trial?: Map<string, string>) =>
    hs.map(h => `${h.address}:${st(h.address)}${trial ? `->${trial.get(h.address) ?? 'MISSING'}` : ''}`).join(',');

  const rows: MemberRow[] = [];
  const candidates: Candidate[] = [];
  const equal: Array<{ row: MemberRow; file: string; holders: RatchetRecord[] }> = [];
  for (const address of [...holdersOf.keys()].sort()) {
    const hs = holdersOf.get(address)!;
    const name = index.fnByAddr.get(address)?.qname ?? names.get(address) ?? '';
    const row = (status: MemberStatus, detail: string, verified = ''): MemberRow =>
      ({ status, address, name, audit: st(address), holders: holderText(hs), verified, detail });
    if (isMatch(st(address))) { rows.push(row('match', 'MATCH itself: never released')); continue; }
    if (roots.has(address)) { rows.push(row('own-record', 'the root of a record of its own: that record decides')); continue; }
    if (released.has(address)) { rows.push(row('already-released', releases.find(r => r.address === address)!.reason)); continue; }
    const loc = locate(index, address);
    if (!loc) { rows.push(row('kept', 'not defined in the measured tree')); continue; }
    const fresh = opts.fresh.get(address);
    if (fresh === undefined || fresh === loc.definition) {
      // The regen kept nothing here: the unit compiles this same text with or without the record.
      const gen = opts.generated ? locate(opts.generated, address) : undefined;
      const same = gen ? gen.definition === loc.definition : undefined;
      const r = row('equal', same === false
        ? 'no kept body in this regen, but the generated tree\'s text differs from the measured one (a hand edit or another regen)'
        : 'the generated body is the kept one: the unit is the same text either way, its records\' bytes cannot change', same ? 'text' : '');
      rows.push(r);
      if (same !== false) equal.push({ row: r, file: loc.file, holders: hs });
      continue;
    }
    const matching = hs.filter(h => isMatch(st(h.address)));
    if (matching.length === 0) { rows.push(row('no-holder', 'no record holding it is MATCH: nothing to verify the fresh body against')); continue; }
    candidates.push({ address, name, audit: st(address), file: loc.file, kept: loc.definition, fresh, holders: matching });
  }

  if (!opts.compiler) {
    for (const c of candidates) rows.push({ status: 'kept', address: c.address, name: c.name, audit: c.audit, holders: holderText(holdersOf.get(c.address)!), verified: '', detail: 'no compiler: a release is never assumed' });
    return sortRows(rows);
  }

  // Round 1: per unit, the unchanged compile and the trial with every candidate of the unit
  // swapped in together (what the next regen would produce); a sample of equal units unchanged.
  const byFile = new Map<string, Candidate[]>();
  for (const c of candidates) byFile.set(c.file, [...(byFile.get(c.file) ?? []), c]);
  const files = [...byFile.keys()].sort();
  const sample: typeof equal = [];
  if (opts.sampleEqual && equal.length > 0) {
    const seen = new Set(files);
    const step = Math.max(1, Math.floor(equal.length / opts.sampleEqual));
    for (let i = 0; i < equal.length && sample.length < opts.sampleEqual; i += step) {
      if (seen.has(equal[i].file)) continue;
      seen.add(equal[i].file);
      sample.push(equal[i]);
    }
  }
  const edit = (cs: Candidate[]): UnitTrial => ({ file: cs[0].file, edits: cs.map(c => ({ from: c.kept, to: c.fresh })) });
  const r1 = await opts.compiler.compile([
    ...files.map(f => ({ file: f, edits: [] })),
    ...files.map(f => edit(byFile.get(f)!)),
    ...sample.map(s => ({ file: s.file, edits: [] })),
  ]);
  const base = new Map(files.map((f, i) => [f, r1[i]]));
  const joint = new Map(files.map((f, i) => [f, r1[files.length + i]]));
  sample.forEach((s, i) => {
    const r = r1[2 * files.length + i];
    const bad = baseProblem(r, s.holders.filter(h => isMatch(st(h.address))));
    s.row.verified = s.row.verified ? `${s.row.verified}+compile` : 'compile';
    s.row.detail += bad ? `; unchanged compile: ${bad}` : '; unchanged compile: every MATCH holder matches';
    if (r.statuses) s.row.holders = holderText(s.holders, r.statuses);
  });

  /** A trial result for candidates cs of one unit: released (empty) or why not. */
  const judge = (cs: Candidate[], b: TrialResult, t: TrialResult): string | undefined => {
    const bp = baseProblem(b, cs.flatMap(c => c.holders));
    if (bp) return bp;
    if (!t.statuses) return `the trial did not compile: ${t.error ?? 'no object'}`;
    const lost = lostIn(b.statuses!, t.statuses);
    return lost.length ? `loses MATCH: ${lost.join(', ')}` : undefined;
  };

  const outcome = new Map<string, { ok: boolean; detail: string; trial?: Map<string, string> }>();
  const retry: string[] = [];
  for (const f of files) {
    const cs = byFile.get(f)!;
    const why = judge(cs, base.get(f)!, joint.get(f)!);
    if (!why) for (const c of cs) outcome.set(c.address, { ok: true, detail: cs.length > 1 ? `with ${cs.length - 1} other member(s) of its unit` : '', trial: joint.get(f)!.statuses });
    else if (cs.length > 1 && !base.get(f)!.error) retry.push(f);
    else for (const c of cs) outcome.set(c.address, { ok: false, detail: why, trial: joint.get(f)!.statuses });
  }
  // Round 2: a unit whose joint trial failed, one candidate at a time; round 3: the ones that
  // pass alone, together again (releasing two members at once is only verified together).
  if (retry.length > 0) {
    const singles = retry.flatMap(f => byFile.get(f)!.map(c => ({ f, c })));
    const r2 = await opts.compiler.compile(singles.map(({ c }) => edit([c])));
    const passing = new Map<string, Candidate[]>();
    singles.forEach(({ f, c }, i) => {
      const why = judge([c], base.get(f)!, r2[i]);
      if (why) outcome.set(c.address, { ok: false, detail: `${why} (alone)`, trial: r2[i].statuses });
      else passing.set(f, [...(passing.get(f) ?? []), c]);
    });
    const many = [...passing].filter(([, cs]) => cs.length > 1);
    for (const [, cs] of passing) if (cs.length === 1) outcome.set(cs[0].address, { ok: true, detail: 'alone; the other members of its unit stay kept', trial: r2[singles.findIndex(s => s.c === cs[0])].statuses });
    if (many.length > 0) {
      const r3 = await opts.compiler.compile(many.map(([, cs]) => edit(cs)));
      many.forEach(([f, cs], i) => {
        const why = judge(cs, base.get(f)!, r3[i]);
        for (const c of cs) outcome.set(c.address, why ? { ok: false, detail: `passes alone, but together: ${why}` } : { ok: true, detail: `with ${cs.length - 1} other member(s) of its unit`, trial: r3[i].statuses });
      });
    }
  }

  const add: Release[] = [];
  for (const c of candidates) {
    const o = outcome.get(c.address)!;
    const all = holdersOf.get(c.address)!;
    const holders = holderText(all, o.trial);
    if (!o.ok) { rows.push({ status: 'kept', address: c.address, name: c.name, audit: c.audit, holders, verified: 'compile', detail: o.detail }); continue; }
    const others = all.filter(h => !c.holders.includes(h));
    const reason = `non-MATCH member (${c.audit}) of ${c.holders.map(h => h.address).join(', ')}: ${c.holders.length > 1 ? 'they stay' : 'it stays'} MATCH with its generated body `
      + `(VC8 trial at evidence ${opts.evidence}${o.detail ? `, ${o.detail}` : ''})${others.length ? `; holders not MATCH: ${others.map(h => `${h.address} ${st(h.address)}`).join(', ')}` : ''}`;
    add.push({ address: c.address, reason, body: bodyHash(c.fresh) });
    rows.push({ status: 'released', address: c.address, name: c.name, audit: c.audit, holders, verified: 'compile', detail: `${reason}; the member itself ${c.audit}->${o.trial?.get(c.address) ?? 'MISSING'}` });
  }
  if (!opts.dryRun && add.length > 0) store.writeReleases([...store.releases(), ...add]);
  return sortRows(rows);
}

function sortRows(rows: MemberRow[]): MemberRow[] {
  const order: MemberStatus[] = ['released', 'kept', 'no-holder', 'already-released', 'own-record', 'equal', 'match'];
  return [...rows].sort((a, b) => order.indexOf(a.status) - order.indexOf(b.status) || a.address.localeCompare(b.address));
}

export function formatMemberReport(rows: MemberRow[]): string {
  const clean = (s: string) => s.replace(/[\t\n]/gu, ' ');
  return `status\taddress\tname\taudit\tholders\tverified\tdetail\n${rows.map(r => [r.status, r.address, r.name, r.audit, r.holders, r.verified, r.detail].map(clean).join('\t')).join('\n')}\n`;
}

export function summarizeMembers(rows: MemberRow[]): Record<MemberStatus, number> {
  const out = { released: 0, kept: 0, equal: 0, match: 0, 'own-record': 0, 'already-released': 0, 'no-holder': 0 } as Record<MemberStatus, number>;
  for (const r of rows) out[r.status]++;
  return out;
}

/** ratchet-fresh.json: address -> generated definition. */
export function readFreshBodies(text: string): Map<string, string> {
  return new Map(Object.entries(JSON.parse(text) as Record<string, string>));
}
