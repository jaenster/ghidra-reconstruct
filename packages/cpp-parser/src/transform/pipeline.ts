/**
 * Create a pipeline that runs transformers until no changes occur
 */
export function createFixpointPipeline<N extends ASTNode = ASTNode>(
  transformers: Transformer<N>[],
  maxIterations: number = 10
): Transformer<N> {
  const combined = sequence(...transformers);

  return (node: N) => {
    let current = node;
    for (let i = 0; i < maxIterations; i++) {
      const result = transformWithTracking(current, combined, { trackChanges: true });
      if (result.changesCount === 0) {
        break;
      }
      current = result.ast;
    }
    return current;
  };
}

/**
 * Create a pipeline that processes nodes in parallel (for independent subtrees)
 * Note: This is a conceptual parallel - actual parallelism would require worker threads
 */
export function createParallelPipeline<N extends ASTNode = ASTNode>(
  transformers: Transformer<N>[]
): Transformer<N> {
  return (node: N) => {
    // Apply all transformers and merge results
    // In practice, this applies them sequentially but allows for future optimization
    let result = node;
    for (const t of transformers) {
      const transformed = t(result);
      if (transformed !== result) {
        result = transformed;
      }
    }
    return result;
  };
}
